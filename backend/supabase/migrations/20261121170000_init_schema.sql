-- Tranche Guard: initial schema (Backend Schema Document, section 5 of the blueprint).
-- Mirrors backend/app/models.py. Applied to the Supabase project Akatsuki_db.
--
-- Access control: the FastAPI backend connects as the "postgres" role and checks
-- the household on every query. Row level security is enabled on every table
-- with NO policy, so Supabase's public Data API (anon / authenticated keys)
-- can read or write nothing. Only the backend can.

create table public.users (
    id            uuid primary key default gen_random_uuid(),
    email         varchar(255) not null unique,
    password_hash varchar(255) not null,
    role          varchar(20)  not null default 'household'
                  constraint users_role_check check (role in ('admin', 'household')),
    created_at    timestamptz  not null default now()
);
comment on table public.users is 'Accounts. Passwords hashed with bcrypt.';

create table public.households (
    id               uuid primary key default gen_random_uuid(),
    user_id          uuid not null references public.users (id) on delete cascade,
    name             varchar(100) not null,
    subscribed_kva   numeric(5, 1) not null constraint households_kva_check check (subscribed_kva > 0),
    alert_margin_kwh integer not null default 10 constraint households_margin_check check (alert_margin_kwh >= 0),
    leak_start_hour  integer not null default 1 constraint households_leak_start_check check (leak_start_hour between 0 and 23),
    leak_end_hour    integer not null default 5 constraint households_leak_end_check check (leak_end_hour between 0 and 23),
    leak_min_minutes integer not null default 120 constraint households_leak_minutes_check check (leak_min_minutes > 0),
    active_device_id varchar(64),
    created_at       timestamptz not null default now()
);
create index households_user_id_idx on public.households (user_id);
comment on table public.households is 'Every record belongs to a household.';

create table public.devices (
    id                 varchar(64) primary key,
    household_id       uuid not null references public.households (id) on delete cascade,
    kind               varchar(20) not null constraint devices_kind_check check (kind in ('esp32', 'simulator')),
    api_key_hash       varchar(64) not null unique,
    calib_pulses_per_l integer not null default 450,
    last_seen_at       timestamptz,
    created_at         timestamptz not null default now()
);
create index devices_household_id_idx on public.devices (household_id);
comment on column public.devices.api_key_hash is 'SHA-256 of the device API key; the key is never stored.';

create table public.readings (
    id               bigint generated by default as identity primary key,
    device_id        varchar(64) not null references public.devices (id) on delete cascade,
    ts               timestamptz not null,
    voltage_v        double precision,
    current_a        double precision,
    power_w          double precision,
    energy_kwh       double precision,
    frequency_hz     double precision,
    power_factor     double precision,
    flow_l_min       double precision,
    water_total_l    double precision,
    pulses_delta     integer,
    signal_ok        boolean not null,
    energy_delta_kwh double precision,
    water_delta_l    double precision,
    step_w           double precision,
    appliance_hint   varchar(60)
);
create index readings_device_ts_idx on public.readings (device_id, ts);
comment on table public.readings is 'One row per JSON payload (every 5 s per device).';

create table public.alerts (
    id              uuid primary key default gen_random_uuid(),
    household_id    uuid not null references public.households (id) on delete cascade,
    type            varchar(20) not null
                    constraint alerts_type_check check (type in ('threshold', 'leak', 'device_offline', 'sensor_fault')),
    resource        varchar(20)
                    constraint alerts_resource_check check (resource is null or resource in ('electricity', 'water')),
    severity        varchar(10) not null default 'warning'
                    constraint alerts_severity_check check (severity in ('info', 'warning', 'critical')),
    message         text not null,
    extra_cost_dt   numeric(10, 3),
    dedupe_key      varchar(160),
    created_at      timestamptz not null default now(),
    acknowledged_at timestamptz,
    constraint alerts_household_dedupe_key unique (household_id, dedupe_key)
);
create index alerts_household_created_idx on public.alerts (household_id, created_at);

create table public.tips (
    id           uuid primary key default gen_random_uuid(),
    household_id uuid not null references public.households (id) on delete cascade,
    code         varchar(40) not null,
    text         text not null,
    saving_dt    numeric(10, 3),
    source       varchar(10) not null default 'rule' constraint tips_source_check check (source in ('rule', 'llm')),
    created_at   timestamptz not null default now()
);
create index tips_household_id_idx on public.tips (household_id);

create table public.scores (
    id           uuid primary key default gen_random_uuid(),
    household_id uuid not null references public.households (id) on delete cascade,
    day          date not null,
    score        integer not null constraint scores_score_check check (score between 0 and 100),
    kwh          numeric(10, 3),
    budget_kwh   numeric(10, 3),
    constraint scores_household_day_key unique (household_id, day)
);

create table public.badges_earned (
    household_id uuid not null references public.households (id) on delete cascade,
    badge_code   varchar(40) not null,
    earned_at    timestamptz not null default now(),
    primary key (household_id, badge_code)
);

create table public.tariff_tranches (
    id             integer generated by default as identity primary key,
    resource       varchar(20) not null
                   constraint tariff_tranches_resource_check check (resource in ('electricity', 'water')),
    min_qty        numeric(12, 3) not null constraint tariff_tranches_min_check check (min_qty >= 0),
    max_qty        numeric(12, 3),
    price_millimes integer not null constraint tariff_tranches_price_check check (price_millimes >= 0),
    vat_rate       numeric(5, 4) not null constraint tariff_tranches_vat_check check (vat_rate >= 0 and vat_rate < 1),
    valid_from     date not null,
    constraint tariff_tranches_max_check check (max_qty is null or max_qty > min_qty),
    constraint tariff_tranches_unique_band unique (resource, valid_from, min_qty)
);
create index tariff_tranches_resource_valid_idx on public.tariff_tranches (resource, valid_from);
comment on table public.tariff_tranches is 'Price per tranche (kWh for electricity, m3 for water). Edit rows, not code.';

create table public.tariff_fees (
    id             integer generated by default as identity primary key,
    key            varchar(80) not null,
    value_millimes numeric(12, 3) not null,
    valid_from     date not null,
    constraint tariff_fees_key_valid_key unique (key, valid_from)
);
create index tariff_fees_key_valid_idx on public.tariff_fees (key, valid_from);
comment on table public.tariff_fees is
    'Fees and taxes. Key prefix elec_/water_ = resource; suffix _per_kva, _per_kwh, _per_m3, _per_month = basis.';

-- Lock the public Data API out of every table (backend-only access).
alter table public.users           enable row level security;
alter table public.households      enable row level security;
alter table public.devices         enable row level security;
alter table public.readings        enable row level security;
alter table public.alerts          enable row level security;
alter table public.tips            enable row level security;
alter table public.scores          enable row level security;
alter table public.badges_earned   enable row level security;
alter table public.tariff_tranches enable row level security;
alter table public.tariff_fees     enable row level security;
