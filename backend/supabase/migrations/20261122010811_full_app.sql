-- Tranche Guard, phase 2: the full application (accounts, several homes, appliances,
-- assistant, support, admin). Mirrors the "(added, phase 2)" parts of app/models.py.
-- Safe on the existing data: every new column has a default or allows NULL.
-- Accounts that existed before sign-up keep working (email_verified defaults to true).

-- Users: profile, language, status, verification, session version, notification preferences.
alter table public.users add column full_name     varchar(120);
alter table public.users add column language      varchar(2)  not null default 'fr';
alter table public.users add column status        varchar(12) not null default 'active';
alter table public.users add column email_verified boolean    not null default true;
alter table public.users add column token_version integer     not null default 0;
alter table public.users add column notify_prefs  jsonb;
alter table public.users add column last_login_at timestamptz;
alter table public.users add constraint users_language_check check (language in ('fr', 'en', 'ar'));
alter table public.users add constraint users_status_check check (status in ('active', 'suspended'));

-- Households: several per account, with address and occupants.
alter table public.households add column address         varchar(200);
alter table public.households add column occupants       integer;
alter table public.households add column onboarding_done boolean not null default true;

-- Numbers of each alert / tip message, so the app can translate it (fr, en, ar).
alter table public.alerts add column params jsonb;
alter table public.tips   add column params jsonb;

-- Appliance profile of a household: an estimate, never a measurement.
create table public.appliances (
    id            uuid primary key default gen_random_uuid(),
    household_id  uuid not null references public.households (id) on delete cascade,
    category      varchar(40) not null,
    name          varchar(80) not null,
    quantity      integer not null default 1 constraint appliances_quantity_check check (quantity between 1 and 100),
    power_w       double precision constraint appliances_power_check check (power_w is null or (power_w > 0 and power_w <= 20000)),
    hours_per_day double precision
                  constraint appliances_hours_check check (hours_per_day is null or (hours_per_day >= 0 and hours_per_day <= 24)),
    start_hour    integer constraint appliances_start_check check (start_hour is null or start_hour between 0 and 23),
    end_hour      integer constraint appliances_end_check check (end_hour is null or end_hour between 0 and 23),
    created_at    timestamptz not null default now()
);
create index appliances_household_id_idx on public.appliances (household_id);

-- One-time codes (email verification, password reset). Only an HMAC of the code is stored.
create table public.auth_codes (
    id         uuid primary key default gen_random_uuid(),
    user_id    uuid not null references public.users (id) on delete cascade,
    purpose    varchar(20) not null
               constraint auth_codes_purpose_check check (purpose in ('verify_email', 'reset_password')),
    code_hash  varchar(64) not null,
    attempts   integer not null default 0,
    expires_at timestamptz not null,
    used_at    timestamptz,
    created_at timestamptz not null default now()
);
create index auth_codes_user_purpose_idx on public.auth_codes (user_id, purpose);

-- Help & support messages. Kept (without the account link) if the account is deleted.
create table public.support_tickets (
    id         uuid primary key default gen_random_uuid(),
    user_id    uuid references public.users (id) on delete set null,
    email      varchar(255) not null,
    category   varchar(30)  not null,
    subject    varchar(150) not null,
    message    text         not null,
    status     varchar(12)  not null default 'open'
               constraint support_tickets_status_check check (status in ('open', 'answered', 'closed')),
    created_at timestamptz  not null default now()
);
create index support_tickets_created_idx on public.support_tickets (created_at);

-- Audit log of every tariff change (who, when, full grid before and after).
create table public.tariff_audit (
    id          bigint generated by default as identity primary key,
    admin_id    uuid references public.users (id) on delete set null,
    admin_email varchar(255) not null,
    summary     text not null,
    before      jsonb,
    after       jsonb,
    created_at  timestamptz not null default now()
);

-- Same rule as the first migration: only the backend can read or write these tables.
alter table public.appliances      enable row level security;
alter table public.auth_codes      enable row level security;
alter table public.support_tickets enable row level security;
alter table public.tariff_audit    enable row level security;
